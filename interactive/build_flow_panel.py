"""Build the data file behind the interactive "one picture" page.

Run from the repo root:
    python interactive/build_flow_panel.py
Writes:
    interactive/data_flow.js      ->  window.ATLAS_FLOW = {...}

What goes in:
  - every company on the Forbes Global 2000 (2026) list, with revenue, profit
    and headcount for every fiscal year from 2001 to 2025;
  - sector, country and industry for each company.

The long history comes from data/global2000_2026_history_panel.csv, which is
stitched out of every Forbes edition (2011-2026) by scripts/build_history_panel.py.
Each edition carries its own ten years of financials, so the 2011 edition
reaches back to fiscal 2001.

This page is separate from data.js on purpose: the year-by-year and ideas
pages stay on the ten years the list itself reports, while the one-picture
page shows the quarter-century the editions allow.

The page itself works out ranks from these arrays, so nothing here is
pre-digested and every number on screen traces back to a row of the panel.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "interactive" / "data_flow.js"

# House palette (data_analysis/config.py) plus the site hues, one per sector.
SECTOR_COLOURS = {
    "Financials": "#1B6CA8",
    "Consumer & Retail": "#E07A4F",
    "Energy & Utilities": "#2E8B74",
    "Technology": "#8A6FB0",
    "Healthcare": "#E34948",
    "Food & Agriculture": "#B8860B",
    "Industrials & Defense": "#4A5563",
    "Construction & Real Estate": "#9CC7E4",
    "Materials & Chemicals": "#C08552",
    "Business Services": "#1B9AAA",
    "Telecom & Media": "#D96BA0",
    "Transport & Logistics": "#7A9A3E",
    "Conglomerates": "#9AA5B1",
    "Unclassified": "#D6DCE5",
}

METRICS = {"revenue": "r", "profits": "p", "employees": "e"}


def key(name: str) -> str:
    """Same normalisation the site uses for names (site/build/ideas.py)."""
    return re.sub(r"[^a-z0-9]", "", str(name).lower())


def main() -> None:
    listing = pd.read_csv(ROOT / "data/global2000_2026.csv", encoding="utf-8-sig",
                          low_memory=False)
    panel = pd.read_csv(ROOT / "data/global2000_2026_history_panel.csv",
                        encoding="utf-8-sig", low_memory=False)

    years = list(range(int(panel.approx_year.min()), int(panel.approx_year.max()) + 1))
    n_years = len(years)

    # metric -> company key -> [value per year]
    series: dict[str, dict[str, list]] = {m: {} for m in METRICS.values()}
    for metric, short in METRICS.items():
        block = panel[panel.metric == metric]
        for name, grp in block.groupby("company", sort=False):
            per_year = [None] * n_years
            for _, r in grp.iterrows():
                per_year[years.index(int(r.approx_year))] = r.value
            series[short][key(name)] = per_year

    sectors = list(SECTOR_COLOURS)
    rows = []
    blank = [None] * n_years

    # one line per company: what the firm actually does (article/data/business_ideas.csv)
    descriptions: dict[str, str] = {}
    ideas_file = ROOT / "article" / "data" / "business_ideas.csv"
    if ideas_file.exists():
        biz = pd.read_csv(ideas_file, encoding="utf-8-sig")
        for name, text in zip(biz.company, biz.what_they_do):
            if pd.isna(text):
                continue
            descriptions.setdefault(key(name), str(text).strip())

    for _, r in listing.iterrows():
        k = key(r.company)
        rows.append({
            "n": r.company,
            "c": r.country,
            "s": sectors.index(r.sector),
            "i": r.industry_canon,
            "v": None if pd.isna(r.market_value_musd) else float(r.market_value_musd),
            "d": descriptions.get(k, ""),
            "r": series["r"].get(k, blank),
            "p": series["p"].get(k, blank),
            "e": series["e"].get(k, blank),
        })

    payload = {
        "years": years,
        "sectors": sectors,
        "colours": [SECTOR_COLOURS[s] for s in sectors],
        "source": ("Forbes Global 2000 (2026) list, with every edition back to 2011 "
                   "stitched into one history"),
        "rows": rows,
    }

    ideas: dict[str, str] = {}
    idea_file = ROOT / "article" / "data" / "idea_sectors.csv"
    if idea_file.exists():
        ideas_df = pd.read_csv(idea_file, encoding="utf-8-sig")
        for _, r in ideas_df.iterrows():
            text = r["the_idea"]
            ideas[r["sector"]] = "" if pd.isna(text) else str(text)
    payload["ideas"] = [ideas.get(s, "") for s in sectors]

    OUT.write_text(
        "/* generated by interactive/build_flow_panel.py - do not edit by hand */\n"
        "window.ATLAS_FLOW = " + json.dumps(payload, separators=(",", ":")) + ";\n",
        encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1e6:.2f} MB)")

    # ---- integrity checks -------------------------------------------------
    print(f"years: {years[0]}-{years[-1]} ({n_years})")
    for metric, short in METRICS.items():
        per_year = [sum(1 for row in rows if row[short][i] is not None) for i in range(n_years)]
        print(f"  {metric:<10} coverage: {per_year}")

    i_last = n_years - 1
    checks = []
    for name in ("Amazon", "Walmart", "NVIDIA", "JPMorganChase"):
        row = next((r for r in rows if r["n"] == name), None)
        checks.append((name, None if row is None else row["r"][i_last]))
    print("  2025 revenue from the panel:", checks)
    print("  2001 firms reporting revenue:", sum(1 for row in rows if row["r"][0] is not None))
    print("  firms with a full 25-year revenue run:",
          sum(1 for row in rows if all(v is not None for v in row["r"])))


if __name__ == "__main__":
    main()
