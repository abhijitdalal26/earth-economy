"""Build the data file behind the interactive "Forbes 2000, year by year" page.

Run from the repo root:
    python interactive/build_time_explorer.py
Writes:
    interactive/data.js      ->  window.ATLAS_TIME = {...}

What goes in:
  - every company on the Forbes Global 2000 (2026) list, with revenue, profit
    and headcount for each year from 2016 to 2025;
  - sector, country and industry for each company.

The page itself works out ranks, sector mix, country mix and concentration
from these arrays, so nothing here is pre-digested and every number on screen
can be traced back to a row of the history file.

Notes on the data:
  - The history file is long format (one row per company, metric, year).
  - "approx_year" is the year the figure was reported for, not the list year.
  - Some metrics are missing for some companies and some years; they stay null
    and the page shows coverage per year instead of pretending they are zero.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "interactive" / "data.js"

YEARS = list(range(2016, 2026))
METRICS = {"revenue": "r", "profits": "p", "employees": "e"}

# House palette (data_analysis/config.py) plus the site hues, one per sector.
SECTOR_COLOURS = {
    "Financials": "#1B6CA8",
    "Consumer & Retail": "#E07A4F",
    "Energy & Utilities": "#2E8B74",
    "Technology": "#8A6FB0",
    "Healthcare": "#E34948",
    "Food & Agriculture": "#B8860B",
    "Industrials & Defense": "#4A5563",
    "Construction & Real Estate": "#9CC7E4",
    "Materials & Chemicals": "#C08552",
    "Business Services": "#1B9AAA",
    "Telecom & Media": "#D96BA0",
    "Transport & Logistics": "#7A9A3E",
    "Conglomerates": "#9AA5B1",
    "Unclassified": "#D6DCE5",
}


def key(name: str) -> str:
    """Same normalisation the site uses for names (site/build/ideas.py)."""
    return re.sub(r"[^a-z0-9]", "", str(name).lower())


def main() -> None:
    g = pd.read_csv(ROOT / "data/global2000_2026.csv", encoding="utf-8-sig")
    h = pd.read_csv(ROOT / "data/global2000_2026_history.csv", encoding="utf-8-sig",
                    low_memory=False)

    h["k"] = h.company.map(key)
    hist: dict[str, dict[str, list]] = {}
    for k, grp in h.groupby("k"):
        d: dict[str, list] = {}
        for metric, short in METRICS.items():
            rows = grp[grp.metric == metric]
            per_year = [None] * len(YEARS)
            for _, r in rows.iterrows():
                i = YEARS.index(int(r.approx_year))
                per_year[i] = r.value
            d[short] = per_year
        hist[k] = d

    sectors = [s for s in SECTOR_COLOURS]
    rows = []
    for _, r in g.iterrows():
        k = key(r.company)
        d = hist.get(k)
        if d is None:
            raise SystemExit(f"no history rows for {r.company}")
        rows.append({
            "n": r.company,
            "c": r.country,
            "s": sectors.index(r.sector),
            "i": r.industry_canon,
            "v": None if pd.isna(r.market_value_musd) else float(r.market_value_musd),
            "r": d["r"],
            "p": d["p"],
            "e": d["e"],
        })

    payload = {
        "years": YEARS,
        "sectors": sectors,
        "colours": [SECTOR_COLOURS[s] for s in sectors],
        "source": "Forbes Global 2000 (2026) list, with 10 years of reported financials",
        "rows": rows,
    }

    # One line per sector: what that business idea is (article/data/idea_sectors.csv).
    ideas: dict[str, str] = {}
    idea_file = ROOT / "article" / "data" / "idea_sectors.csv"
    if idea_file.exists():
        ideas_df = pd.read_csv(idea_file, encoding="utf-8-sig")
    for _, r in ideas_df.iterrows():
        text = r["the_idea"]
        ideas[r["sector"]] = "" if pd.isna(text) else str(text)
    payload["ideas"] = [ideas.get(s, "") for s in sectors]
    OUT.write_text(
        "/* generated by interactive/build_time_explorer.py - do not edit by hand */\n"
        "window.ATLAS_TIME = " + json.dumps(payload, separators=(",", ":")) + ";\n",
        encoding="utf-8")

    # ---- integrity checks -------------------------------------------------
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1e6:.2f} MB)")
    for metric, short in METRICS.items():
        per_year = [sum(1 for row in rows if row[short][i] is not None) for i in range(len(YEARS))]
        print(f"  {metric:<10} coverage by year: {per_year}")

    # The last history year should line up with the list's own current figures.
    i_last = len(YEARS) - 1
    checks = []
    for name in ("Amazon", "Walmart", "NVIDIA", "JPMorganChase"):
        row = next((r for r in rows if r["n"] == name), None)
        checks.append((name, None if row is None else row["r"][i_last]))
    print("  2025 revenue from history:", checks)

    cur = g.set_index(g.company.map(key))
    diffs = []
    for row in rows:
        k = key(row["n"])
        if k in cur.index and row["r"][i_last] is not None:
            listed = cur.loc[k, "revenue_musd"]
            if pd.notna(listed) and listed:
                diffs.append(abs(row["r"][i_last] - listed) / listed)
    s = pd.Series(diffs)
    print(f"  revenue 2025 vs the list's own figure: {len(s)} firms, "
          f"median gap {s.median() * 100:.2f}%, 90th pct {s.quantile(0.9) * 100:.2f}%")
    print(f"  firms matching within 1%: {(s < 0.01).sum()} / {len(s)}")


if __name__ == "__main__":
    main()
